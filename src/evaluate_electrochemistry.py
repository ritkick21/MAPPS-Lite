def load_data():
    """
    Load screened MAPPS-Lite candidates and retrieved electrode data.
    """

    if not SCREENED_FILE.exists():
        raise FileNotFoundError(
            f"Missing screened materials file:\n{SCREENED_FILE}"
        )

    if not ELECTRODE_MATCHES_FILE.exists():
        raise FileNotFoundError(
            "Missing electrode matches file:\n"
            f"{ELECTRODE_MATCHES_FILE}\n\n"
            "Run:\n"
            "python src/electrochemical_features.py --limit 0"
        )

    screened = pd.read_csv(
        SCREENED_FILE
    )

    matches = pd.read_csv(
        ELECTRODE_MATCHES_FILE
    )

    required_screened_columns = {
        "material_id",
        "formula",
        "screening_status",
    }

    missing = (
        required_screened_columns
        - set(screened.columns)
    )

    if missing:
        raise ValueError(
            "screened_materials.csv is missing: "
            + ", ".join(sorted(missing))
        )

    return screened, matches


# =========================================================
# NUMERIC HELPERS
# =========================================================

def to_float(value):
    """
    Convert a value to float.

    Returns None for missing or invalid values.
    """

    if value is None:
        return None

    try:
        if pd.isna(value):
            return None

        number = float(value)

        if math.isnan(number):
            return None

        return number

    except (ValueError, TypeError):
        return None


def clamp(value, minimum=0.0, maximum=100.0):
    """
    Restrict a score to the 0-100 range.
    """

    return max(
        minimum,
        min(maximum, value),
    )


def interpolate_score(value, points):
    """
    Piecewise-linear interpolation.

    points should contain tuples:

        (physical_value, score)

    Example:

        [
            (2.0, 0),
            (3.0, 60),
            (3.5, 100),
        ]
    """

    if value is None:
        return None

    points = sorted(
        points,
        key=lambda item: item[0],
    )

    if value <= points[0][0]:
        return float(points[0][1])

    if value >= points[-1][0]:
        return float(points[-1][1])

    for index in range(
        len(points) - 1
    ):
        x1, y1 = points[index]
        x2, y2 = points[index + 1]

        if x1 <= value <= x2:
            fraction = (
                (value - x1)
                / (x2 - x1)
            )

            score = (
                y1
                + fraction
                * (y2 - y1)
            )

            return float(score)

    return None


# =========================================================
# SCIENTIFIC SUB-SCORES
# =========================================================

def calculate_voltage_score(voltage):
    """
    Evaluate average cathode voltage.

    The scoring favors roughly 3.5-4.3 V.

    Very low voltages reduce energy density.

    Extremely high voltages are not automatically rewarded because
    high-voltage operation can create electrolyte and structural
    stability challenges.
    """

    return interpolate_score(
        voltage,
        [
            (1.5, 0),
            (2.0, 15),
            (2.5, 35),
            (3.0, 65),
            (3.5, 100),
            (4.0, 100),
            (4.3, 100),
            (4.5, 85),
            (5.0, 45),
            (5.5, 10),
            (6.0, 0),
        ],
    )


def calculate_capacity_score(capacity):
    """
    Evaluate gravimetric capacity in mAh/g.

    Larger capacity generally increases stored charge per unit mass.
    """

    return interpolate_score(
        capacity,
        [
            (0, 0),
            (50, 10),
            (100, 50),
            (150, 75),
            (200, 100),
            (300, 100),
        ],
    )


def calculate_energy_score(energy):
    """
    Evaluate gravimetric specific energy in Wh/kg.
    """

    return interpolate_score(
        energy,
        [
            (0, 0),
            (150, 10),
            (300, 40),
            (500, 75),
            (700, 100),
            (1000, 100),
        ],
    )


def calculate_volume_score(volume_change):
    """
    Evaluate structural volume change during cycling.

    Smaller structural changes are preferred because large expansion
    or contraction may contribute to mechanical degradation.
    """

    if volume_change is None:
        return None

    volume_change = abs(
        volume_change
    )

    return interpolate_score(
        volume_change,
        [
            (0, 100),
            (5, 100),
            (10, 85),
            (15, 65),
            (25, 35),
            (40, 0),
            (100, 0),
        ],
    )


def calculate_stability_score(
    stability_charge,
    stability_discharge,
):
    """
    Evaluate thermodynamic stability.

    Materials Project stability values correspond to energy above
    hull for the charged and discharged endpoint materials.

    The less-stable endpoint is used so that a highly unstable
    charged or discharged phase cannot be hidden by a stable
    opposite endpoint.
    """

    available = []

    if stability_charge is not None:
        available.append(
            stability_charge
        )

    if stability_discharge is not None:
        available.append(
            stability_discharge
        )

    if not available:
        return None

    worst_stability = max(
        available
    )

    return interpolate_score(
        worst_stability,
        [
            (0.00, 100),
            (0.025, 100),
            (0.05, 85),
            (0.10, 55),
            (0.20, 20),
            (0.30, 0),
            (1.00, 0),
        ],
    )


def calculate_voltage_step_score(
    num_steps,
):
    """
    Score the complexity of the voltage profile.

    Fewer distinct stable intermediate steps receive a modest
    preference.

    This has intentionally low weight because multi-step behavior
    is not inherently disqualifying.
    """

    if num_steps is None:
        return None

    return interpolate_score(
        num_steps,
        [
            (1, 100),
            (2, 90),
            (3, 75),
            (4, 60),
            (5, 50),
            (8, 30),
            (12, 20),
        ],
    )


# =========================================================
# MATERIAL-ID MATCHING
# =========================================================

def extract_material_ids(value):
    """
    Extract Materials Project IDs such as mp-12345 from an electrode
    material_ids field.
    """

    if value is None:
        return set()

    try:
        if pd.isna(value):
            return set()
    except TypeError:
        pass

    text = str(value)

    ids = re.findall(
        r"mp-\d+",
        text,
    )

    return set(ids)


def determine_match_type(
    candidate_material_id,
    electrode_material_ids,
):
    """
    Determine whether the exact candidate structure participates in
    the Materials Project electrode pathway.

    DIRECT_STRUCTURE_MATCH:
        The candidate's exact mp-ID appears in the electrode path.

    FORMULA_FAMILY_MATCH:
        Materials Project contains an electrode system associated
        with the formula, but this exact mp-ID is not present.
    """

    material_ids = extract_material_ids(
        electrode_material_ids
    )

    if candidate_material_id in material_ids:
        return "DIRECT_STRUCTURE_MATCH"

    return "FORMULA_FAMILY_MATCH"


# =========================================================
# LITHIUM CHANGE
# =========================================================

def calculate_lithium_fraction_change(
    fraction_charge,
    fraction_discharge,
):
    """
    Calculate the change in lithium atomic fraction between charged
    and discharged endpoint compositions.
    """

    if (
        fraction_charge is None
        or fraction_discharge is None
    ):
        return None

    return (
        fraction_discharge
        - fraction_charge
    )


# =========================================================
# ELECTROCHEMICAL SCORE
# =========================================================

def evaluate_electrode_record(
    candidate_material_id,
    record,
):
    """
    Score one Materials Project electrode record.

    The final score is a weighted screening score.

    It is NOT a prediction of real experimental cycle life,
    rate capability, safety, or commercial viability.
    """

    voltage = to_float(
        record.get(
            "average_voltage_V"
        )
    )

    capacity = to_float(
        record.get(
            "capacity_grav_mAh_g"
        )
    )

    energy = to_float(
        record.get(
            "energy_grav_Wh_kg"
        )
    )

    volume_change = to_float(
        record.get(
            "max_volume_change_percent"
        )
    )

    stability_charge = to_float(
        record.get(
            "stability_charge_eV_atom"
        )
    )

    stability_discharge = to_float(
        record.get(
            "stability_discharge_eV_atom"
        )
    )

    num_steps = to_float(
        record.get(
            "num_voltage_steps"
        )
    )

    fraction_charge = to_float(
        record.get(
            "li_fraction_charge"
        )
    )

    fraction_discharge = to_float(
        record.get(
            "li_fraction_discharge"
        )
    )

    scores = {
        "voltage":
            calculate_voltage_score(
                voltage
            ),

        "capacity":
            calculate_capacity_score(
                capacity
            ),

        "energy":
            calculate_energy_score(
                energy
            ),

        "volume_change":
            calculate_volume_score(
                volume_change
            ),

        "stability":
            calculate_stability_score(
                stability_charge,
                stability_discharge,
            ),

        "voltage_steps":
            calculate_voltage_step_score(
                num_steps
            ),
    }

    weighted_total = 0.0
    available_weight = 0.0
    available_metrics = 0

    for metric, score in scores.items():

        if score is None:
            continue

        weight = WEIGHTS[metric]

        weighted_total += (
            score * weight
        )

        available_weight += weight
        available_metrics += 1

    if available_weight == 0:
        raw_score = None
        completeness = 0.0
        adjusted_score = None

    else:
        raw_score = (
            weighted_total
            / available_weight
        )

        completeness = (
            available_metrics
            / len(WEIGHTS)
        )

        # ---------------------------------------------
        # Reduce confidence when only a small portion
        # of the desired electrochemical data exists.
        # ---------------------------------------------

        confidence_factor = (
            0.50
            + 0.50 * completeness
        )

        adjusted_score = (
            raw_score
            * confidence_factor
        )

    match_type = determine_match_type(
        candidate_material_id,
        record.get(
            "electrode_material_ids"
        ),
    )

    lithium_fraction_change = (
        calculate_lithium_fraction_change(
            fraction_charge,
            fraction_discharge,
        )
    )

    return {
        "database_match_type":
            match_type,

        "electrochemical_score_raw":
            raw_score,

        "electrochemical_score":
            adjusted_score,

        "electrochemical_data_completeness":
            completeness,

        "voltage_score":
            scores["voltage"],

        "capacity_score":
            scores["capacity"],

        "energy_score":
            scores["energy"],

        "volume_change_score":
            scores["volume_change"],

        "stability_score":
            scores["stability"],

        "voltage_steps_score":
            scores["voltage_steps"],

        "li_fraction_change":
            lithium_fraction_change,
    }


# =========================================================
# RATING
# =========================================================

def determine_electrochemical_rating(
    score,
):
    """
    Convert the electrochemical score into an interpretable category.
    """

    if score is None:
        return "UNVERIFIED"

    if score >= 80:
        return "HIGH_PRIORITY"

    if score >= 65:
        return "PROMISING"

    if score >= 50:
        return "MODERATE"

    return "LOW_PRIORITY"


# =========================================================
# SELECT BEST ELECTRODE RECORD
# =========================================================

def select_best_record(
    candidate_material_id,
    candidate_matches,
):
    """
    Evaluate every matching electrode record and select the strongest
    scientifically relevant record.

    Direct structural matches are preferred over formula-only matches.

    If multiple direct matches exist, the highest-scoring one is used.
    """

    evaluated_records = []

    for _, record in (
        candidate_matches.iterrows()
    ):

        evaluation = (
            evaluate_electrode_record(
                candidate_material_id,
                record,
            )
        )

        combined = record.to_dict()

        combined.update(
            evaluation
        )

        evaluated_records.append(
            combined
        )

    if not evaluated_records:
        return None

    direct_records = [
        record
        for record in evaluated_records
        if record[
            "database_match_type"
        ] == "DIRECT_STRUCTURE_MATCH"
    ]

    if direct_records:
        pool = direct_records
    else:
        pool = evaluated_records

    def ranking_score(record):
        score = record.get(
            "electrochemical_score"
        )

        if score is None:
            return -1

        return score

    return max(
        pool,
        key=ranking_score,
    )


