# MARKDOWN TABLE
# =========================================================

def format_value(value, decimals=2):
    """
    Format values for the Markdown report.
    """

    if value is None:
        return "-"

    try:
        if pd.isna(value):
            return "-"
    except TypeError:
        pass

    if isinstance(
        value,
        (float, int),
    ):
        return f"{value:.{decimals}f}"

    return str(value)


def create_markdown_table(rows):
    """
    Build a small Markdown table without requiring the optional
    'tabulate' Python dependency.
    """

    header = (
        "| Rank | Material | Formula | Evidence | "
        "Score | Voltage (V) | Capacity (mAh/g) | "
        "Energy (Wh/kg) | Volume Δ (%) | Rating |\n"
    )

    separator = (
        "|---:|---|---|---|---:|---:|---:|---:|---:|---|\n"
    )

    lines = [
        header,
        separator,
    ]

    for _, row in rows.iterrows():

        line = (
            f"| {row.get('week5_electrochemical_rank', '-')} "
            f"| {row.get('material_id', '-')} "
            f"| {row.get('formula', '-')} "
            f"| {row.get('database_match_type', '-')} "
            f"| {format_value(row.get('electrochemical_score'), 1)} "
            f"| {format_value(row.get('average_voltage_V'))} "
            f"| {format_value(row.get('capacity_grav_mAh_g'), 1)} "
            f"| {format_value(row.get('energy_grav_Wh_kg'), 1)} "
            f"| {format_value(row.get('max_volume_change_percent'), 1)} "
            f"| {row.get('electrochemical_rating', '-')} |\n"
        )

        lines.append(
            line
        )

    return "".join(lines)


