# SORT RESULTS
# =========================================================

def sort_evaluation(evaluation):
    """
    Sort verified candidates by electrochemical score while preserving
    unverified candidates at the bottom.
    """

    evidence_order = {
        "DIRECT_STRUCTURE_MATCH": 0,
        "FORMULA_FAMILY_MATCH": 1,
        "NO_MP_ELECTRODE_RECORD": 2,
    }

    evaluation[
        "_evidence_order"
    ] = (
        evaluation[
            "database_match_type"
        ]
        .map(evidence_order)
        .fillna(3)
    )

    evaluation = evaluation.sort_values(
        by=[
            "_evidence_order",
            "electrochemical_score",
            "original_rank",
        ],
        ascending=[
            True,
            False,
            True,
        ],
        na_position="last",
    )

    evaluation = evaluation.drop(
        columns=[
            "_evidence_order"
        ]
    )

    evaluation.insert(
        0,
        "week5_electrochemical_rank",
        range(
            1,
            len(evaluation) + 1,
        ),
    )

    return evaluation


